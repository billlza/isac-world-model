def dataset(seeds: list[int], cfg: ExperimentConfig):
    features, means, sigmas, observations, labels = [], [], [], [], []
    for seed in seeds:
        world = SyntheticWorld.create(seed, "same" if seed % 2 == 0 else "different")
        anchor, _ = world.initial_rf()
        rng = np.random.default_rng(np.random.SeedSequence([seed, 882]))
        record = [[], [], [], []]
        position = 0.0
        for step in range(cfg.steps):
            lateral = float(rng.choice([-cfg.max_baseline_m, 0, cfg.max_baseline_m]))
            capture = (
                anchor.available_s
                + step * cfg.slot_s
                + abs(lateral - position) / cfg.camera_speed_mps
                + cfg.exposure_s
            )
            action = {"lateral_m": lateral, "capture_s": capture, "available_s": capture + cfg.delivery_s}
            mean, sigma, feature = observation_geometry(anchor, lateral, capture, cfg)
            observation = world.measure(anchor, action, step, cfg)
            if observation is None:
                raise RuntimeError("Nominal training renderer unexpectedly produced no detection")
            for values, item in zip(record, (feature, mean, sigma, observation), strict=True):
                values.append(item)
            position = lateral
        for collection, values in zip((features, means, sigmas, observations), record, strict=True):
            collection.append(values)
        labels.append(seed % 2)
    return {
        "features": torch.tensor(np.array(features), dtype=torch.float32),
        "means": torch.tensor(np.array(means), dtype=torch.float32),
        "sigmas": torch.tensor(np.array(sigmas), dtype=torch.float32),
        "observations": torch.tensor(np.array(observations), dtype=torch.float32),
        "labels": torch.tensor(labels, dtype=torch.long),
    }


def sequence_loss(
    model: ObservationNetwork,
    data: dict[str, torch.Tensor],
    *,
    rejection_sigma: float = 3.0,
):
    batch, steps = data["observations"].shape
    memory = torch.zeros(batch, 2, model.hidden_size)
    losses = []
    for t in range(steps):
        features, base, sigma = data["features"][:, t], data["means"][:, t], data["sigmas"][:, t]
        prediction, scale = model.predict(features, base, sigma, memory)
        observation = data["observations"][:, t, None]
        nll = 0.5 * ((observation - prediction) / scale) ** 2 + torch.log(scale * (2 * torch.pi) ** 0.5)
        # Labels select the supervised candidate only here, never at inference.
        losses.append(nll.gather(1, data["labels"][:, None]).mean())
        # Match HypothesisMemory.release: candidate-set compatibility gates only
        # the next recurrent state. All current-step supervised NLLs remain,
        # including observations incompatible with every candidate.
        compatible = (((observation - prediction).abs() / scale) <= rejection_sigma).any(dim=-1)
        updated_memory = model.observe(features, base, observation, memory)
        memory = torch.where(compatible[:, None, None], updated_memory, memory)
    return torch.stack(losses).mean()


def train_observer(
    train, validation, *, use_memory: bool, epochs: int, seed: int, rejection_sigma: float = 3.0
):
    torch.manual_seed(seed)
    model = ObservationNetwork(use_memory)
    optimizer = torch.optim.AdamW(model.parameters(), lr=0.003)
    best, selected, history = float("inf"), None, []
    for epoch in range(epochs):
        order = torch.randperm(len(train["labels"]))
        model.train()
        train_values = []
        for indices in order.split(16):
            optimizer.zero_grad()
            loss = sequence_loss(
                model, {k: v[indices] for k, v in train.items()}, rejection_sigma=rejection_sigma
            )
            if not bool(torch.isfinite(loss)):
                raise FloatingPointError("Non-finite observation learning loss")
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 5.0, error_if_nonfinite=True)
            optimizer.step()
            train_values.append(float(loss.detach()))
        model.eval()
        with torch.no_grad():
            value = float(sequence_loss(model, validation, rejection_sigma=rejection_sigma))
        if not np.isfinite(value):
            raise FloatingPointError("Non-finite held-out validation loss")
        history.append(
            {"epoch": epoch + 1, "train_nll": float(np.mean(train_values)), "validation_nll": value}
        )
        if value < best:
            best, selected = value, copy.deepcopy(model.state_dict())
    if selected is None:
        raise RuntimeError("No model selected")
    model.load_state_dict(selected)
    return model.eval(), {"selected_validation_nll": best, "epochs": history, "initialization_seed": seed}


def aggregate(records: list[dict]):
    groups = []
    for scenario in SCENARIOS:
        for method in METHODS:
            rows = [r["metrics"] for r in records if r["scenario"] == scenario and r["method"] == method]
            if not rows:
                raise ValueError("Missing required scenario/method results")
            group = {"scenario": scenario, "method": method, "episodes": len(rows)}
            for field in (
                "wrong_confirmation",
                "ever_wrong_confirmation",
                "abstained",
                "candidate_set_rejected",
                "capture_count",
                "travel_m",
                "late_packets",
                "missing_detections",
                "camera_transport_bits_reserved",
                "remaining_raw_payload_bits_proxy",
            ):
                group[field] = float(np.mean([r[field] for r in rows]))
            # Undefined metrics remain null with an explicit denominator.
            for field in ("first_correct_confirmation_s", "mean_predictive_nll"):
                values = [r[field] for r in rows if r[field] is not None]
                group[field] = float(np.mean(values)) if values else None
                group[field + "_count"] = len(values)
            groups.append(group)
    return groups


def run_study(
    out: Path,
    *,
    train_episodes: int = 64,
    validation_episodes: int = 16,
    test_episodes: int = 4,
    epochs: int = 12,
    seed: int = 20261028,
    planner: str = "verification-aware",
):
    counts = (train_episodes, validation_episodes, test_episodes, epochs)
    if any(type(n) is not int or not 1 <= n <= 512 for n in counts):
        raise ValueError("Study dimensions must be integers in [1,512]")
    if type(seed) is not int or not 0 <= seed < 2**32 - 20512:
        raise ValueError("Invalid seed")
    if planner not in PLANNERS:
        raise ValueError("Unknown planner")
    out = Path(out)
    if out.exists():
        raise FileExistsError("Study output already exists; evidence must not be overwritten")
    out.mkdir(parents=True)
    cfg = ExperimentConfig()
    # Whole episodes, disjoint seed ranges. Test data never select weights.
    splits = {
        "train": list(range(seed, seed + train_episodes)),
        "validation": list(range(seed + 10000, seed + 10000 + validation_episodes)),
        "test": list(range(seed + 20000, seed + 20000 + test_episodes)),
    }
    started = time.perf_counter()
    provenance = {
        "schema_version": 1,
        "status": "running",
        "config": asdict(cfg),
        "splits": splits,
        "epochs": epochs,
        "planner": planner,
        "evidence_protocol": (
            "two candidate-set-compatible (any candidate), geometrically informative detections "
            "after any contradiction; consecutive rejection; historical candidate weights retained; "
            "all-candidates-incompatible observations retain NLL but do not update weights or recurrent state"
        ),
        "base_commit": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
        "source_sha256": {name: sha256_file(ROOT / name) for name in SOURCE_FILES},
        "runtime": {
            "python": platform.python_version(),
            "numpy": np.__version__,
            "torch": torch.__version__,
            "device": "cpu",
            "platform": platform.platform(),
            "threads": torch.get_num_threads(),
        },
        "initialization": "random; no pretrained models",
        "selection": "minimum whole-episode validation NLL",
    }
    write_json(out / "manifest.json", provenance)
    try:
        print("Generating small, waveform-derived training/validation episodes...", flush=True)
        train, validation = dataset(splits["train"], cfg), dataset(splits["validation"], cfg)
        provenance["data_sha256"] = {
            split: {key: hashlib.sha256(tensor.numpy().tobytes()).hexdigest() for key, tensor in data.items()}
            for split, data in (("train", train), ("validation", validation))
        }
        models, learning = {}, {}
        for method, use_memory in (("learned_memory", True), ("learned_no_memory", False)):
            model, history = train_observer(
                train,
                validation,
                use_memory=use_memory,
                epochs=epochs,
                seed=seed + 77,
                rejection_sigma=cfg.rejection_sigma,
            )
            models[method], learning[method] = model, history
            save_checkpoint(
                out / f"{method}.pt",
                {
                    "schema_version": 1,
                    "kind": "active-observation-residual-v1",
                    "use_memory": use_memory,
                    "state_dict": model.state_dict(),
                    "source_sha256": provenance["source_sha256"],
                    "splits": splits,
                },
            )
            print(f"{method}: validation NLL={history['selected_validation_nll']:.4f}", flush=True)
        records = []
        for scenario in SCENARIOS:
            for test_seed in splits["test"]:
                world = SyntheticWorld.create(test_seed, scenario)
                anchor, phy = world.initial_rf()
                for method in METHODS:
                    record = run_episode(
                        world,
                        method,
                        cfg,
                        anchor=anchor,
                        phy_report=phy,
                        network=models.get(method),
                        planner=planner,
                    )
                    record["initial_phy"] = phy
                    records.append(record)
            print(f"Completed all methods: {scenario}", flush=True)
        provenance.update(status="completed", elapsed_s=time.perf_counter() - started)
        provenance["checkpoint_sha256"] = {m: sha256_file(out / f"{m}.pt") for m in models}
        report = {
            "schema_version": 1,
            "kind": "active-observation-study",
            "provenance": provenance,
            "hypotheses": ["same_depth", "farther_object"],
            "learning": learning,
            "summary": aggregate(records),
            "episodes": records,
            "limitations": [
                "Synthetic point scatterer and rendered bearing cue; no natural images or hardware calibration",
                "Learning is a residual observation distribution with recurrent bearing memory, not the full RGB/RF world model",
                "Two proposed depths; all-candidates-wrong rejection uses an uncalibrated innovation gate",
                "Classical repeated likelihoods approximate independence despite shared RF anchor errors",
                "Verification uses explicit evidence-count rules and view diversity; not optimal VoI or independent evidence",
                "legacy-voi retains the old action objective but shares the corrected evidence protocol",
                "One outstanding camera request; delays are declared simulation inputs, not measured execution latency",
                "Communication proxy repeats initial OFDM raw payload capacity and reserves 1024 bits per camera message; not delivered goodput",
                "All methods share time/travel caps but may spend different resources; inspect achieved costs alongside error",
                "Small held-out smoke study is not statistical superiority, material recognition, or autonomous safety evidence",
            ],
        }
        write_json(out / "study.json", report)
        # A compact representative replay per scenario/method, retaining complete
        # aggregate outcomes and hashes. No success-only example selection.
        replay = dict(report)
        replay["episodes"] = [r for r in records if r["seed"] == splits["test"][0]]
        replay["replay_selection"] = "first predeclared held-out seed, every scenario and method"
        write_json(out / "matlab_replay.json", replay)
        write_json(out / "manifest.json", provenance)
        return report
    except Exception as error:
        provenance.update(status="failed", failure_type=type(error).__name__, failure=str(error))
        write_json(out / "manifest.json", provenance)
        raise


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--train-episodes", type=int, default=64)
    parser.add_argument("--validation-episodes", type=int, default=16)
    parser.add_argument("--test-episodes", type=int, default=4)
    parser.add_argument("--epochs", type=int, default=12)
    parser.add_argument("--seed", type=int, default=20261028)
    parser.add_argument("--planner", choices=PLANNERS, default="verification-aware")
    args = parser.parse_args()
    torch.set_num_threads(2)
    report = run_study(**vars(args))
    print(json.dumps({"out": str(args.out), "episodes": len(report["episodes"]), "status": "completed"}))


if __name__ == "__main__":
    main()
